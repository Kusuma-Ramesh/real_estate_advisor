"""Reproducible data-quality audit.  Run: python -m src.audit  ->  reports/data_audit.md"""
import os
import numpy as np
import pandas as pd
from src.features import REFERENCE_YEAR, REQUIRED_COLS, load_raw


def _ks_uniform(x):
    """KS distance to a uniform distribution over the observed range (numpy only)."""
    v = np.sort(((x - x.min()) / (x.max() - x.min())).to_numpy())
    i = np.arange(1, len(v) + 1)
    return float(max((i / len(v) - v).max(), (v - (i - 1) / len(v)).max()))


def _eta2(df, group, y):
    """Share of variance in y explained by a categorical column (0 = none)."""
    g = df.groupby(group)[y]
    between = (g.size() * (g.mean() - df[y].mean()) ** 2).sum()
    return float(between / ((df[y] - df[y].mean()) ** 2).sum())


def main(path="data/india_housing_prices.csv"):
    raw = load_raw(path)
    L = ["# Data audit (generated by `python -m src.audit`)", ""]
    add = lambda k, v: L.append(f"- **{k}:** {v}")
    add("Rows / columns", f"{len(raw):,} / {raw.shape[1]}")
    add("Missing values (total cells)", int(raw.isna().sum().sum()))
    add("Rows with non-positive size or price", int(((raw.Size_in_SqFt <= 0) | (raw.Price_in_Lakhs <= 0)).sum()))
    add("Missing required columns", [c for c in REQUIRED_COLS if c not in raw.columns] or "none")
    add("Duplicate rows ignoring ID", int(raw.drop(columns="ID").duplicated().sum()))
    s = (raw.Age_of_Property + raw.Year_Built)
    add("Date consistency", f"Age_of_Property + Year_Built takes values {sorted(s.unique().tolist())} "
        f"(reference year {REFERENCE_YEAR}); Year_Built range {raw.Year_Built.min()}-{raw.Year_Built.max()}. "
        "The pipeline recomputes age from Year_Built against this single reference year.")
    f_gt = int((raw.Floor_No > raw.Total_Floors).sum())
    add("Floor_No > Total_Floors", f"{f_gt:,} rows ({f_gt/len(raw):.1%}) - impossible physically; kept and flagged via "
        "`Floor_Inconsistent`, ratio capped at 1. Dropping them would discard almost half the data; repairing them would invent data.")
    add("Floor_No == 0 (ground floor)", f"{int((raw.Floor_No == 0).sum()):,} rows - valid")
    rec = raw.Price_in_Lakhs / raw.Size_in_SqFt
    add("Source Price_per_SqFt", f"in lakhs, rounded to 2 dp ({int((raw.Price_per_SqFt == 0).sum()):,} rows are 0.0, "
        f"max rounding error {float((rec - raw.Price_per_SqFt).abs().max()):.3f} lakh/sqft); recomputed in rupees/sqft as `Price_per_SqFt_Rs`.")
    lc = raw.groupby("Locality").City.nunique()
    add("Locality ids", f"{raw.Locality.nunique()} ids; {int((lc > 1).sum())} appear in more than one city (median {lc.median():.0f} cities) "
        "-> not a geographic hierarchy; excluded from models.")
    add("City -> State", f"{int((raw.groupby('City').State.nunique() > 1).sum())} cities map to more than one state (consistent)")
    tok = raw.Amenities.str.split(",").explode().str.strip().value_counts()
    add("Amenity tokens", tok.to_dict())
    num = raw[["BHK", "Size_in_SqFt", "Price_in_Lakhs", "Age_of_Property", "Nearby_Schools", "Nearby_Hospitals", "Floor_No", "Total_Floors"]]
    c = num.corr().abs().where(~np.eye(num.shape[1], dtype=bool))
    add("Largest |correlation| among raw numeric attributes", f"{np.nanmax(c.values):.4f} -> columns look independent (synthetic).")
    add("Corr(price, size)", f"{raw.Price_in_Lakhs.corr(raw.Size_in_SqFt):.4f}")
    # ---- synthetic-pattern and plausibility checks (reported, not "fixed": they need real data)
    L += ["", "## Synthetic patterns and implausible combinations", ""]
    add("Near-uniform numeric columns (KS distance to uniform; 0 = perfectly uniform)",
        {c: round(_ks_uniform(raw[c]), 4) for c in ("Size_in_SqFt", "Price_in_Lakhs", "Year_Built")})
    shares = {c: f"{raw[c].value_counts(normalize=True).min():.1%}-{raw[c].value_counts(normalize=True).max():.1%}"
              for c in ("State", "Property_Type", "BHK", "Furnished_Status", "Facing", "Owner_Type", "Availability_Status")}
    add("Category shares (min-max)", f"{shares} -> near-perfectly balanced, unlike real listings")
    per_bhk = raw.Size_in_SqFt / raw.BHK
    add("BHK vs size", f"corr {raw.BHK.corr(raw.Size_in_SqFt):.3f}; {int(((raw.BHK == 1) & (raw.Size_in_SqFt >= 3000)).sum()):,} one-BHK "
        f"listings of 3,000+ sq ft; {int(((raw.BHK == 5) & (raw.Size_in_SqFt <= 800)).sum()):,} five-BHK listings of 800 sq ft or less; "
        f"sq ft per BHK spans {per_bhk.min():.0f}-{per_bhk.max():.0f}")
    uc = raw[raw.Availability_Status == "Under_Construction"]
    add("Under_Construction vs build year", f"{len(uc):,} under-construction listings have Year_Built {uc.Year_Built.min()}-{uc.Year_Built.max()}; "
        f"{int((uc.Year_Built <= 2010).sum()):,} were 'built' in 2010 or earlier - contradictory")
    house = raw.Property_Type.isin(["Independent House", "Villa"])
    add("Houses/villas in tall buildings", f"{int((house & (raw.Total_Floors > 3)).sum()):,} of {int(house.sum()):,} houses/villas have Total_Floors > 3")
    ppsf = raw.Price_in_Lakhs * 1e5 / raw.Size_in_SqFt
    add("Price per sq ft (INR)", f"range {ppsf.min():,.0f}-{ppsf.max():,.0f}; {(ppsf < 1000).mean():.1%} of rows under 1,000 and "
        f"{(ppsf > 50000).mean():.1%} over 50,000")
    add("Variance in price explained by (eta squared)", {c: round(_eta2(raw, c, "Price_in_Lakhs"), 5)
        for c in ("City", "State", "Property_Type", "BHK", "Furnished_Status", "Availability_Status")})
    L += ["", "## Fixes applied vs. issues that cannot be fixed", "",
          "**Applied (safe, nothing invented):** exact-duplicate check (none found); source price per sq ft recomputed in INR; age recomputed from "
          "Year_Built against one reference year; impossible floors flagged (`Floor_Inconsistent`) with the ratio capped, rows kept; "
          "app input validation and warnings for floors, future build years, out-of-range values, under-construction/old-building and unusual size-per-BHK entries.", "",
          "**Not fixable without better data:** the uniform/balanced distributions, the lack of any BHK-size or price-attribute relationship, "
          "under-construction listings with old build years, houses in tall buildings, extreme price per sq ft values. Dropping or 'repairing' these rows "
          "would either discard most of the data or fabricate values, so they are retained and disclosed. Conclusions drawn from this data "
          "describe the dataset, not real markets."]
    L += ["", "## Consequence", "",
          "Price is statistically unrelated to every other attribute, so a regressor cannot learn price from them and "
          "real-market conclusions cannot be drawn. No future-price or investment-outcome column exists, so the 5-year price "
          "and 'good investment' label are assumption/rule based."]
    os.makedirs("reports", exist_ok=True)
    open("reports/data_audit.md", "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
